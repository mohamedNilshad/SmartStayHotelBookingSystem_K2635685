    private void searchFieldFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_searchFieldFocusGained
        if (searchField.getText().equals(placeholder)) {
            searchField.setText("");
            searchField.setForeground(Color.BLACK); // Change back to normal typing color
        }
    }//GEN-LAST:event_searchFieldFocusGained

    private void searchFieldFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_searchFieldFocusLost
        if (searchField.getText().isEmpty()) {
            searchField.setText(placeholder);
            searchField.setForeground(Color.GRAY);
        }
    }//GEN-LAST:event_searchFieldFocusLost

    private void searchFieldKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchFieldKeyReleased
        String text = searchField.getText().trim();
        List<RoomType> tempRoomTypes;
        if (text.isEmpty()) {
            sortedRoomTypes = DataModels.getRoomTypes();

        } else {

            sortedRoomTypes.clear();

            for (RoomType type : roomTypes) {
                if (type.getName().toLowerCase().startsWith(text.toLowerCase())) {
                    sortedRoomTypes.add(type);
                }
            }
        }

        tabelHeader.setText(sortedRoomTypes.size() + " rooms available");

        // Update UI
        roomListPanel.updateRoomList(sortedRoomTypes);
    }//GEN-LAST:event_searchFieldKeyReleased


