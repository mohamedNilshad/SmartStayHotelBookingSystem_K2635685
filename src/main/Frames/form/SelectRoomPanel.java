    private void setForm() {
        roomTypeDropDown.removeAllItems();
        bedTypeDropDown.removeAllItems();

        for (RoomType type : allRoomTypes) {
            roomTypeDropDown.addItem(type.getName());
        }

        for (String bedType : selectedRoomType.getBedTypes()) {
            bedTypeDropDown.addItem(bedType);
        }

        roomTypeDropDown.setSelectedItem(selectedRoomType.getName());
    }

