    private void setForm() {
        //set fields value
        roomPackageDropDown.removeAllItems();
        bedTypeDropDown.removeAllItems();

        for (K2635685_RoomPackage roomPackage : K2635685_RoomManager.getRoomPackageList()) {
            roomPackageDropDown.addItem(roomPackage.getPackageName());
        }

        for (String bedType : K2635685_RoomManager.getBedTypes()) {
            bedTypeDropDown.addItem(bedType);
        }

        roomPackageDropDown.setSelectedItem(selectedRoom.getRoomPackage().getPackageName());
        bedTypeDropDown.setSelectedItem(selectedRoom.getBedType());

        numberOfGuest.setText(String.valueOf(selectedRoom.getCapacity()));
        discountRateField.setText(String.valueOf(selectedRoom.getDiscountRate()));
        breakFastCheckbox.setSelected(selectedRoom.getBreakfast());
        roomIdLbl.setText(selectedRoom.getRoomIDString());
        updateBtn.setEnabled(false);
     
    }

    private void enableButton() {

        
        boolean fieldsNotNull = roomPackageDropDown.getSelectedItem() != null
                && bedTypeDropDown.getSelectedItem() != null
                && numberOfGuest.getText() != null
                && discountRateField.getText() != null;

        if (fieldsNotNull) {
            
            boolean packageChanged = !selectedRoom.getRoomPackage().getPackageName().equals(roomPackageDropDown.getSelectedItem().toString());
            boolean bedChanged = !selectedRoom.getBedType().equals(bedTypeDropDown.getSelectedItem().toString());
            boolean guestsChanged = !numberOfGuest.getText().equals(String.valueOf(selectedRoom.getCapacity()));
            boolean discountChanged = !discountRateField.getText().equals(String.valueOf(selectedRoom.getDiscountRate()));
            boolean breakFastChanged = !(breakFastCheckbox.isSelected() == selectedRoom.getBreakfast());

            isChanged = packageChanged || bedChanged || guestsChanged || breakFastChanged || discountChanged;
            updateBtn.setEnabled(isChanged);
        }
    }

