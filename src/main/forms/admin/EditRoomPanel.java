    private void discountRateFieldKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_discountRateFieldKeyReleased
        String value = discountRateField.getText().trim();
        boolean isValid = ValidationFunctions.validateDoubleValue(this, value);
        if (!isValid) {
            discountRateField.setText(String.valueOf(selectedRoom.getDiscountRate()));
            discountRateField.requestFocus();
        } else {
            if(Double.parseDouble(value) > 100 || Double.parseDouble(value) < 0){
                HelperFunctions.showPopMessage(this, "Please select a value between 0 - 100", "Invalid value");
                discountRateField.setText(String.valueOf(selectedRoom.getDiscountRate()));
                discountRateField.requestFocus();
            }else{
                enableButton();
            }
        }
    }//GEN-LAST:event_discountRateFieldKeyReleased

