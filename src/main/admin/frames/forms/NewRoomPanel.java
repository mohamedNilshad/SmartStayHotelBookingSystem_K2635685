    private void nogMinusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_nogMinusActionPerformed
        int value = Integer.parseInt(numberOfGuest.getText());
        if (value > 1) {
            value--;
            numberOfGuest.setText(String.valueOf(value));
        }
    }//GEN-LAST:event_nogMinusActionPerformed

    private void nogPlusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_nogPlusActionPerformed
        int value = Integer.parseInt(numberOfGuest.getText());
        if (value < 10) {
            value++;
            numberOfGuest.setText(String.valueOf(value));
        }
    }//GEN-LAST:event_nogPlusActionPerformed

    private void addNewBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addNewBtnActionPerformed
        int roomId = RoomManager.generateRoomId();
        RoomPackage roomPackage = RoomManager.getRoomPackageByName(roomPackageDropDown.getSelectedItem().toString());
        String bedType = bedTypeDropDown.getSelectedItem().toString();
        String[] roomStatus = RoomManager.getRoomStatus();
        boolean breakfast = breakFastCheckbox.isSelected();
        int capacity = Integer.parseInt(numberOfGuest.getText());
        double discountRate = Double.parseDouble(discountRateField.getText());
        
        Room newRoom = new Room(roomId, roomPackage, bedType, roomStatus[0], breakfast,capacity, discountRate);
        RoomManager.addNewRoom(newRoom);
        
        HelperFunctions.showPopMessage(this, "Room created successfully !!", "Created Success");
        onNewRoom.accept(newRoom);
        
    }//GEN-LAST:event_addNewBtnActionPerformed

